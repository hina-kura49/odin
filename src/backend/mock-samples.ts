/** 数百ブロックのページ。見出し・段落・リスト・コード・表を繰り返す */
function longPage(sections: number): string {
  const parts: string[] = []
  for (let i = 1; i <= sections; i++) {
    parts.push(
      `## セクション ${i}`,
      `これはセクション ${i} の本文です。日本語と English が混ざった段落で、**太字** や \`code\` も含みます。`,
      `- 項目 ${i}-1\n- 項目 ${i}-2\n- [ ] タスク ${i}`,
      `> 引用 ${i}`,
      i % 5 === 0 ? `\`\`\`ts\nconst section${i} = ${i} // セクション ${i}\n\`\`\`` : `段落 ${i} の続き。`,
    )
  }
  return `${parts.join('\n\n')}\n`
}

